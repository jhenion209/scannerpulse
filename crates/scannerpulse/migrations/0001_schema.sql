-- ScannerPulse schema, first version.
-- Later migrations are additive: two versions run side by side in a rolling update.

CREATE TABLE systems (
    id   smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE sites (
    id        smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    system_id smallint NOT NULL REFERENCES systems (id),
    name      text NOT NULL,
    UNIQUE (system_id, name)
);

-- name is the recorder's name; ingest updates it.
-- transcribe is off for a talkgroup seen for the first time.
CREATE TABLE talkgroups (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    system_id  smallint NOT NULL REFERENCES systems (id),
    number     bigint NOT NULL,
    name       text NOT NULL,
    transcribe boolean NOT NULL DEFAULT false,
    UNIQUE (system_id, number)
);

-- A recording file is found at root + rel_path.
CREATE TABLE locations (
    id         smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL UNIQUE,
    root       text NOT NULL,
    mode       text NOT NULL CONSTRAINT locations_mode CHECK (mode IN ('managed', 'readonly')),
    is_primary boolean NOT NULL DEFAULT false,
    CONSTRAINT locations_primary_is_managed CHECK (NOT is_primary OR mode = 'managed')
);
CREATE UNIQUE INDEX locations_one_primary ON locations (is_primary) WHERE is_primary;

-- One row per ingest path; also the answer to "where did this call come from".
CREATE TABLE sources (
    id      smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    text NOT NULL UNIQUE,
    kind    text NOT NULL,
    path    text NOT NULL,
    enabled boolean NOT NULL DEFAULT true
);

-- One partition per month; bounds are UTC month starts (see ensure_month_partitions).
-- title is set only when the recorder's title says more than the talkgroup (a patch).
-- file_mtime is the file's modification time as recorded at import.
CREATE TABLE calls (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    started_at       timestamptz NOT NULL,
    duration_ms      integer,
    talkgroup_id     integer REFERENCES talkgroups (id),
    site_id          smallint REFERENCES sites (id),
    radio_id         bigint,
    radio_alias      text,
    title            text,
    source_id        smallint NOT NULL REFERENCES sources (id),
    location_id      smallint NOT NULL REFERENCES locations (id),
    rel_path         text NOT NULL,
    file_mtime       timestamptz,
    transcript_state text NOT NULL DEFAULT 'untried'
        CONSTRAINT calls_transcript_state CHECK (transcript_state IN ('untried', 'no_speech', 'text')),
    PRIMARY KEY (id, started_at),
    UNIQUE (location_id, rel_path, started_at)
) PARTITION BY RANGE (started_at);

CREATE INDEX calls_listing ON calls (started_at DESC, id DESC);
CREATE INDEX calls_talkgroup_listing ON calls (talkgroup_id, started_at DESC, id DESC);

-- search keeps one rule: every run of non-alphanumeric characters separates words.
CREATE TABLE transcripts (
    call_id    bigint NOT NULL,
    started_at timestamptz NOT NULL,
    text       text NOT NULL,
    search     tsvector GENERATED ALWAYS AS (
                   to_tsvector('simple'::regconfig, regexp_replace(text, '[^[:alnum:]]+', ' ', 'g'))
               ) STORED,
    origin     text NOT NULL CONSTRAINT transcripts_origin CHECK (origin IN ('machine', 'human')),
    model      text,
    updated_at timestamptz,
    PRIMARY KEY (call_id, started_at),
    FOREIGN KEY (call_id, started_at) REFERENCES calls (id, started_at) ON DELETE CASCADE
) PARTITION BY RANGE (started_at);

CREATE INDEX transcripts_search ON transcripts USING gin (search);

-- Text a person saved for a call. machine_text is the first machine output.
CREATE TABLE transcript_labels (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    call_id      bigint NOT NULL,
    started_at   timestamptz NOT NULL,
    text         text NOT NULL,
    machine_text text,
    source       text NOT NULL,
    labeler      text,
    created_at   timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (call_id, started_at) REFERENCES calls (id, started_at) ON DELETE CASCADE
);
CREATE INDEX transcript_labels_call ON transcript_labels (call_id, id);

CREATE TABLE favorites (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE favorite_talkgroups (
    favorite_id  bigint NOT NULL REFERENCES favorites (id) ON DELETE CASCADE,
    talkgroup_id integer NOT NULL REFERENCES talkgroups (id),
    PRIMARY KEY (favorite_id, talkgroup_id)
);

-- Creates the calls and transcripts partitions for the month that contains the
-- given date, if they do not exist. Bounds are the first instant of the month
-- and of the next month in UTC, independent of the session's time zone.
CREATE FUNCTION ensure_month_partitions(any_day date) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
    month_start date := date_trunc('month', any_day)::date;
    month_end   date := (date_trunc('month', any_day) + interval '1 month')::date;
    lo     timestamptz := make_timestamptz(extract(year FROM month_start)::int, extract(month FROM month_start)::int, 1, 0, 0, 0, 'UTC');
    hi     timestamptz := make_timestamptz(extract(year FROM month_end)::int, extract(month FROM month_end)::int, 1, 0, 0, 0, 'UTC');
    suffix text := to_char(month_start, '"y"YYYY"m"MM');
BEGIN
    EXECUTE format('CREATE TABLE IF NOT EXISTS %I PARTITION OF calls FOR VALUES FROM (%L) TO (%L)',
                   'calls_' || suffix, lo, hi);
    EXECUTE format('CREATE TABLE IF NOT EXISTS %I PARTITION OF transcripts FOR VALUES FROM (%L) TO (%L)',
                   'transcripts_' || suffix, lo, hi);
END
$$;
