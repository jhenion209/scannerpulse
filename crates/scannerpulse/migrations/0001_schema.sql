-- ScannerPulse schema, first version.
-- Later migrations are additive: two versions run side by side in a rolling update.

-- Ids that ingest looks up for every call are integer, not smallint: an
-- INSERT ... ON CONFLICT uses up an identity value on every conflict, so a
-- get-or-create per call would exhaust smallint within days.
CREATE TABLE systems (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE sites (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    system_id integer NOT NULL REFERENCES systems (id),
    name      text NOT NULL,
    UNIQUE (system_id, name)
);

-- name is the recorder's name; ingest updates it.
-- transcribe is off for a talkgroup seen for the first time.
CREATE TABLE talkgroups (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    system_id  integer NOT NULL REFERENCES systems (id),
    number     bigint NOT NULL,
    name       text NOT NULL,
    transcribe boolean NOT NULL DEFAULT false,
    UNIQUE (system_id, number)
);

-- A recording file is found at root + rel_path.
CREATE TABLE locations (
    id         smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL UNIQUE,
    root       text NOT NULL,
    mode       text NOT NULL CONSTRAINT locations_mode CHECK (mode IN ('managed', 'readonly')),
    is_primary boolean NOT NULL DEFAULT false,
    CONSTRAINT locations_primary_is_managed CHECK (NOT is_primary OR mode = 'managed')
);
CREATE UNIQUE INDEX locations_one_primary ON locations (is_primary) WHERE is_primary;

-- One row per ingest path; also the answer to "where did this call come from".
CREATE TABLE sources (
    id      smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    text NOT NULL UNIQUE,
    kind    text NOT NULL,
    path    text NOT NULL,
    enabled boolean NOT NULL DEFAULT true
);

-- One partition per month; bounds are UTC month starts (see ensure_month_partitions).
-- One file is one call per month, through each partition's own UNIQUE (location_id, rel_path).
-- title is set only when the recorder's title says more than the talkgroup (a patch).
-- file_mtime is the file's modification time as recorded at import.
CREATE TABLE calls (
    -- The primary key contains started_at, so id alone is unique only because the
    -- database hands it out: ordinary code must not supply one.
    id               bigint GENERATED ALWAYS AS IDENTITY,
    started_at       timestamptz NOT NULL,
    duration_ms      integer,
    talkgroup_id     integer REFERENCES talkgroups (id),
    site_id          integer REFERENCES sites (id),
    radio_id         bigint,
    radio_alias      text,
    title            text,
    source_id        smallint NOT NULL REFERENCES sources (id),
    location_id      smallint NOT NULL REFERENCES locations (id),
    rel_path         text NOT NULL,
    file_mtime       timestamptz,
    transcript_state text NOT NULL DEFAULT 'untried'
        CONSTRAINT calls_transcript_state CHECK (transcript_state IN ('untried', 'no_speech', 'text')),
    PRIMARY KEY (id, started_at)
) PARTITION BY RANGE (started_at);

CREATE INDEX calls_listing ON calls (started_at DESC, id DESC);
CREATE INDEX calls_talkgroup_listing ON calls (talkgroup_id, started_at DESC, id DESC);

-- search keeps one rule: every run of non-alphanumeric characters separates words.
CREATE TABLE transcripts (
    call_id    bigint NOT NULL,
    started_at timestamptz NOT NULL,
    text       text NOT NULL,
    search     tsvector GENERATED ALWAYS AS (
                   to_tsvector('simple'::regconfig, regexp_replace(text, '[^[:alnum:]]+', ' ', 'g'))
               ) STORED,
    origin     text NOT NULL CONSTRAINT transcripts_origin CHECK (origin IN ('machine', 'human')),
    model      text,
    updated_at timestamptz,
    PRIMARY KEY (call_id, started_at),
    FOREIGN KEY (call_id, started_at) REFERENCES calls (id, started_at) ON DELETE CASCADE
) PARTITION BY RANGE (started_at);

CREATE INDEX transcripts_search ON transcripts USING gin (search);

-- Text a person saved for a call. machine_text is the first machine output. Deleted with its call.
CREATE TABLE transcript_labels (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    call_id      bigint NOT NULL,
    started_at   timestamptz NOT NULL,
    text         text NOT NULL,
    machine_text text,
    source       text NOT NULL,
    labeler      text,
    created_at   timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (call_id, started_at) REFERENCES calls (id, started_at) ON DELETE CASCADE
);
CREATE INDEX transcript_labels_call ON transcript_labels (call_id, id);

CREATE TABLE favorites (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE favorite_talkgroups (
    favorite_id  bigint NOT NULL REFERENCES favorites (id) ON DELETE CASCADE,
    talkgroup_id integer NOT NULL REFERENCES talkgroups (id),
    PRIMARY KEY (favorite_id, talkgroup_id)
);

-- Creates the calls and transcripts partitions for the month that contains the
-- given date, if they do not exist. any_day is a UTC date: pass
-- (instant AT TIME ZONE 'UTC')::date. Bounds are the first instant of that
-- month and of the next month in UTC, whatever the session's settings.
--
-- Each calls partition refuses a second call for the same file in the same
-- location. The partitioned table cannot do that itself: its unique
-- constraints must contain started_at.
--
-- Safe to call from several sessions at once: callers queue on an advisory
-- lock. When both partitions exist the call returns at once and takes no lock.
-- Creating a partition locks calls and transcripts exclusively, and locks the
-- tables that calls refers to against writes, until the caller's transaction
-- ends: call this function in a transaction of its own. A wait for any of
-- these locks ends after lock_timeout. Try again after a lock timeout or a
-- deadlock.
--
-- A new partition is given the owner of its parent, whoever calls this
-- function: a later ALTER TABLE on the parent changes every partition and
-- must own each one.
CREATE FUNCTION ensure_month_partitions(any_day date) RETURNS void
LANGUAGE plpgsql
SET timezone = 'UTC'
SET datestyle = 'ISO, YMD'
SET lock_timeout = '10s'
AS $$
DECLARE
    lo      timestamptz := date_trunc('month', any_day::timestamp)::timestamptz;
    hi      timestamptz := lo + interval '1 month';
    suffix  text := to_char(lo, '"y"YYYY"m"MM');
    parent  text;
    part    text;
BEGIN
    IF to_regclass('calls_' || suffix) IS NOT NULL
       AND to_regclass('transcripts_' || suffix) IS NOT NULL THEN
        RETURN;
    END IF;
    -- Advisory lock 1 of this program: one partition creator at a time.
    PERFORM pg_advisory_xact_lock(1397048658, 1);
    FOREACH parent IN ARRAY ARRAY['calls', 'transcripts'] LOOP
        part := parent || '_' || suffix;
        -- IF NOT EXISTS although the lock is held: a session that waited for
        -- the lock may still remember the partition as missing.
        EXECUTE format('CREATE TABLE IF NOT EXISTS %I PARTITION OF %I %s FOR VALUES FROM (%L) TO (%L)',
                       part, parent,
                       CASE WHEN parent = 'calls' THEN '(UNIQUE (location_id, rel_path))' ELSE '' END,
                       lo, hi);
        IF (SELECT c.relowner <> p.relowner FROM pg_class c, pg_class p
            WHERE c.oid = part::regclass AND p.oid = parent::regclass) THEN
            EXECUTE format('ALTER TABLE %I OWNER TO %I', part,
                           (SELECT pg_get_userbyid(relowner) FROM pg_class WHERE oid = parent::regclass));
        END IF;
    END LOOP;
END
$$;
